#!/usr/bin/env node
/**
 * Build output baseline script.
 *
 * Captures a snapshot of the built web-apps output for diffing across
 * build system changes. Run against the deployed output directory.
 *
 * Usage:
 *   node baseline.js [output-dir] [--write] [--diff baseline.json] [--scan-tokens]
 *
 * output-dir:    path to web-apps/apps (default: /var/www/onlyoffice/documentserver/web-apps/apps)
 * --write:       write snapshot to baseline.json in cwd
 * --diff <f>:    compare current output against a saved baseline.json
 * --scan-tokens: scan .js and .css output files for unreplaced {{TOKEN}} strings
 *
 * Tiers:
 *   1. MODULE MANIFEST  — named define() calls extracted from each JS bundle.
 *                         Catches dropped/duplicated modules deterministically.
 *   2. STATIC HASHES    — SHA-256 of files that must not change: locale JSON,
 *                         SVG, GIF, ICO, .htm help docs. NOT JS, CSS, or HTML
 *                         (those are minified/inlined and tool-dependent).
 *   3. BUNDLE SIZES     — byte size of JS and CSS bundles with ±15% tolerance.
 *                         Floor: a bundle <50% of baseline size is always a failure.
 *   4. FILE PRESENCE    — every file in the baseline must exist in the comparison.
 *                         New files are reported but not failed.
 */

'use strict';

const fs   = require('fs');
const path = require('path');
const crypto = require('crypto');

const DEFAULT_DIR = '/var/www/onlyoffice/documentserver/web-apps/apps';
const SIZE_TOLERANCE = 0.15;  // ±15%
const SIZE_FLOOR     = 0.50;  // <50% of baseline is always a hard failure

// DefinePlugin rewrites bare AST identifiers only — it cannot reach {{TOKEN}} inside string literals.
// Any surviving mustache token in .js/.css output is an absolute build failure, no baseline needed.
// .json is excluded: locale files use {{...}} for runtime i18n interpolation (not a bug).
const TOKEN_RE   = /\{\{[A-Z][A-Z0-9_]*\}\}/g;
const TOKEN_EXTS = new Set(['.js', '.css']);

// --- CLI args ---
const args      = process.argv.slice(2);
const writeFlag = args.includes('--write');
const scanFlag  = args.includes('--scan-tokens');
const diffIdx   = args.indexOf('--diff');
const diffFile  = diffIdx !== -1 ? args[diffIdx + 1] : null;
const dirArg    = args.find(a => !a.startsWith('--') && a !== (diffFile || ''));
const ROOT      = dirArg ? path.resolve(dirArg) : DEFAULT_DIR;

if (!fs.existsSync(ROOT)) {
    console.error(`ERROR: directory not found: ${ROOT}`);
    process.exit(1);
}

// --- Helpers ---
function sha256(filePath) {
    const data = fs.readFileSync(filePath);
    return crypto.createHash('sha256').update(data).digest('hex');
}

function walkDir(dir, results = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walkDir(full, results);
        else results.push(full);
    }
    return results;
}

function relPath(full) {
    return path.relative(ROOT, full);
}

function extractModules(filePath) {
    const content = fs.readFileSync(filePath, 'utf8');
    const matches = content.match(/define\("([^"]+)"/g) || [];
    return matches.map(m => m.replace('define("', '').replace('"', '')).sort();
}

// File classification
const HASH_EXTS    = new Set(['.gif', '.ico', '.htm']);
const SIZE_EXTS    = new Set(['.js', '.css']);
const SKIP_EXTS    = new Set(['.map']);  // source maps change with every bundler run
const BUNDLE_NAMES = new Set(['app.js', 'app-all.js', 'code.js']);

// Paths whose SVGs are generated (svg_sprite) — vary with source, not bundler
const GENERATED_SVG_DIRS = ['resources/img/toolbar', 'resources/img/sprites'];

function isGeneratedSvg(relFilePath) {
    return GENERATED_SVG_DIRS.some(d => relFilePath.includes(d));
}

function classify(filePath, relFilePath) {
    const ext  = path.extname(filePath).toLowerCase();
    const base = path.basename(filePath);
    if (SKIP_EXTS.has(ext)) return 'skip';
    if (base.endsWith('.js.map') || base.endsWith('.css.map')) return 'skip';
    if (ext === '.html') return 'size';   // grunt-inline embeds minified JS into HTML
    if (ext === '.json') return 'size';   // locale files change frequently; not bundler-dependent
    if (ext === '.svg' && isGeneratedSvg(relFilePath)) return 'size'; // generated by svg_sprite
    if (ext === '.js' && BUNDLE_NAMES.has(base)) return 'bundle'; // extract modules too
    if (SIZE_EXTS.has(ext)) return 'size';
    if (ext === '.svg') return 'hash';    // static SVGs (copied, not generated)
    if (HASH_EXTS.has(ext)) return 'hash';
    return 'size'; // default: track size for anything else (.png, .txt, etc.)
}

// --- Token scan ---
function scanTokens(dir) {
    const files    = walkDir(dir);
    const findings = [];
    for (const full of files) {
        const ext = path.extname(full).toLowerCase();
        if (!TOKEN_EXTS.has(ext)) continue;
        const content = fs.readFileSync(full, 'utf8');
        TOKEN_RE.lastIndex = 0;
        const tokens = new Set();
        let m;
        while ((m = TOKEN_RE.exec(content)) !== null) tokens.add(m[0]);
        if (tokens.size) findings.push({ file: relPath(full), tokens: [...tokens].sort() });
    }
    return findings;
}

// --- Capture snapshot ---
function capture() {
    const files = walkDir(ROOT);
    const snapshot = {
        generated: new Date().toISOString(),
        root: ROOT,
        summary: { total: 0, bundles: 0, hashed: 0, sized: 0, skipped: 0 },
        bundles: {},   // module manifests + sizes for main JS bundles
        hashes: {},    // sha256 for stable static files
        sizes: {},     // byte sizes for everything else
        skipped: []    // source maps etc.
    };

    for (const full of files) {
        const rel  = relPath(full);
        const stat = fs.statSync(full);
        const size = stat.size;
        const type = classify(full, rel);

        snapshot.summary.total++;

        if (type === 'skip') {
            snapshot.skipped.push(rel);
            snapshot.summary.skipped++;
        } else if (type === 'bundle') {
            const modules = extractModules(full);
            snapshot.bundles[rel] = { size, modules, moduleCount: modules.length };
            snapshot.summary.bundles++;
        } else if (type === 'hash') {
            snapshot.hashes[rel] = { size, sha256: sha256(full) };
            snapshot.summary.hashed++;
        } else {
            snapshot.sizes[rel] = size;
            snapshot.summary.sized++;
        }
    }

    return snapshot;
}

// --- Diff two snapshots ---
function diff(baseline, current) {
    const issues  = [];
    const notices = [];

    // Tier 1: module manifests
    for (const [rel, base] of Object.entries(baseline.bundles)) {
        const cur = current.bundles[rel];
        if (!cur) {
            issues.push(`MISSING BUNDLE: ${rel}`);
            continue;
        }
        const baseSet = new Set(base.modules);
        const curSet  = new Set(cur.modules);
        const dropped = [...baseSet].filter(m => !curSet.has(m));
        const added   = [...curSet].filter(m => !baseSet.has(m));
        if (dropped.length) issues.push(`MODULES DROPPED from ${rel}: ${dropped.join(', ')}`);
        if (added.length)   notices.push(`modules added to ${rel}: ${added.join(', ')}`);
    }

    // Tier 2: static hashes
    for (const [rel, base] of Object.entries(baseline.hashes)) {
        const cur = current.hashes[rel];
        if (!cur) {
            issues.push(`MISSING FILE: ${rel}`);
            continue;
        }
        if (base.sha256 !== cur.sha256) {
            issues.push(`HASH CHANGED: ${rel} (expected ${base.sha256.slice(0,8)}… got ${cur.sha256.slice(0,8)}…)`);
        }
    }

    // Tier 3: bundle sizes
    for (const [rel, base] of Object.entries(baseline.bundles)) {
        const cur = current.bundles[rel];
        if (!cur) continue; // already caught above
        const ratio = cur.size / base.size;
        if (ratio < SIZE_FLOOR) {
            issues.push(`BUNDLE TOO SMALL: ${rel} — ${cur.size} bytes vs baseline ${base.size} (${Math.round(ratio*100)}%)`);
        } else if (ratio < (1 - SIZE_TOLERANCE) || ratio > (1 + SIZE_TOLERANCE)) {
            notices.push(`bundle size outside ±${Math.round(SIZE_TOLERANCE*100)}%: ${rel} — ${cur.size} vs ${base.size} (${Math.round(ratio*100)}%)`);
        }
    }

    // Tier 4: file presence
    const baseFiles = new Set([
        ...Object.keys(baseline.bundles),
        ...Object.keys(baseline.hashes),
        ...Object.keys(baseline.sizes)
    ]);
    const curFiles = new Set([
        ...Object.keys(current.bundles),
        ...Object.keys(current.hashes),
        ...Object.keys(current.sizes)
    ]);
    for (const f of baseFiles) {
        if (!curFiles.has(f) && !baseline.skipped.includes(f)) {
            if (!issues.some(i => i.includes(f))) {
                issues.push(`MISSING FILE: ${f}`);
            }
        }
    }
    for (const f of curFiles) {
        if (!baseFiles.has(f)) notices.push(`new file: ${f}`);
    }

    return { issues, notices, passed: issues.length === 0 };
}

// --- Main ---
if (scanFlag) {
    console.log(`Scanning for unreplaced {{TOKEN}} strings in ${ROOT}...`);
    const findings = scanTokens(ROOT);
    if (findings.length === 0) {
        console.log('\nResult: PASSED — no unreplaced tokens found');
    } else {
        console.log('\nFAILURES:');
        for (const { file, tokens } of findings) {
            console.log(`  ✗ ${file}`);
            for (const t of tokens) console.log(`      ${t}`);
        }
        const total = findings.reduce((n, f) => n + f.tokens.length, 0);
        console.log(`\nResult: FAILED — ${total} unreplaced token(s) in ${findings.length} file(s)`);
        process.exit(1);
    }
} else if (diffFile) {
    if (!fs.existsSync(diffFile)) {
        console.error(`ERROR: baseline file not found: ${diffFile}`);
        process.exit(1);
    }
    const baseline = JSON.parse(fs.readFileSync(diffFile, 'utf8'));
    console.log(`Capturing current snapshot from ${ROOT}...`);
    const current = capture();
    console.log(`Diffing against ${diffFile}...`);
    const result = diff(baseline, current);

    if (result.notices.length) {
        console.log('\nNOTICES:');
        result.notices.forEach(n => console.log('  •', n));
    }
    if (result.issues.length) {
        console.log('\nFAILURES:');
        result.issues.forEach(i => console.log('  ✗', i));
        console.log(`\nResult: FAILED (${result.issues.length} issue(s))`);
        process.exit(1);
    } else {
        console.log('\nResult: PASSED — build output is equivalent');
    }
} else {
    console.log(`Capturing snapshot from ${ROOT}...`);
    const snapshot = capture();
    console.log(`\nSummary:`);
    console.log(`  Total files:    ${snapshot.summary.total}`);
    console.log(`  JS bundles:     ${snapshot.summary.bundles}`);
    console.log(`  Hashed files:   ${snapshot.summary.hashed}`);
    console.log(`  Sized files:    ${snapshot.summary.sized}`);
    console.log(`  Skipped:        ${snapshot.summary.skipped}`);
    console.log(`\nBundle module counts:`);
    for (const [rel, b] of Object.entries(snapshot.bundles)) {
        console.log(`  ${b.moduleCount.toString().padStart(4)} modules  ${rel}`);
    }

    if (writeFlag) {
        const outFile = path.join(process.cwd(), 'baseline.json');
        fs.writeFileSync(outFile, JSON.stringify(snapshot, null, 2));
        console.log(`\nBaseline written to ${outFile}`);
    } else {
        console.log('\n(Pass --write to save as baseline.json)');
    }
}
